## 1. 개요: 왜 Dual DB (MySQL + Oracle 26ai) 구조인가?

운영 중인 백엔드 시스템에 AI 임베딩 벡터 검색(Vector Search / Semantic Search)을 도입할 때, 기존 메인 데이터베이스(MySQL 8.0)를 전체 마이그레이션하지 않고 **MSA(Microservice Architecture) 원칙에 따라 역할을 분리**하는 이원화 DB 아키텍처를 선택했습니다.

| 구분 | API Microservice (:api) | Worker Microservice (:ai-worker) |
| :--- | :--- | :--- |
| **역할** | 유저, 경험, 스터디, 자소서 기본 CRUD 및 조회 | AI 채용공고 수집, 텍스트 벡터화, 시맨틱 검색 |
| **데이터베이스** | **MySQL 8.0** (기존 인프라 유지) | **Oracle Autonomous DB 26ai** (신규 구축) |
| **접속 방식** | OCI VCN Private Subnet Direct JDBC | OCI ATP Wallet (mTLS 보안 인증서) |
| **특징** | 고성능 트랜잭션 (OLTP) | **Native VECTOR 타입 & VECTOR_DISTANCE 쿼리** |

