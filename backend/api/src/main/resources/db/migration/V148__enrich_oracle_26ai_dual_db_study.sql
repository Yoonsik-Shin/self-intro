## 6. 1536차원 임베딩 벡터 변환 (`VectorEmbeddingService.java`)

OpenAI `text-embedding-3-small` API를 호출하여 텍스트를 1536차원 `float[]` 배열로 변환하고, Oracle 26ai VECTOR 호환 문자열 `\"[0.012, -0.045, ...]\"` 형식으로 포맷팅합니다.

```java
@Service
public class VectorEmbeddingService {

    private final EmbeddingModel embeddingModel;

    /**
     * Oracle 26ai VECTOR 호환 문자열 변환: \"[0.012345, -0.045678, ...]\"
     */
    public String embedToVectorString(String text) {
        float[] embedding = embeddingModel.embed(text);
        if (embedding != null && embedding.length > 0) {
            return formatAsOracleVectorString(embedding);
        }
        return generateFallbackVectorString(text); // 로컬: 해시 기반 결정론적 폴백
    }

    private String formatAsOracleVectorString(float[] vector) {
        StringBuilder sb = new StringBuilder(\"[\");
        for (int i = 0; i < vector.length; i++) {
            sb.append(String.format(Locale.US, \"%.6f\", vector[i]));
            if (i < vector.length - 1) sb.append(\",\");
        }
        return sb.append(\"]\").toString();
    }
}
```

**폴백 전략**: API 호출 실패 시 텍스트 해시 기반 **결정론적 1536차원 단위벡터**를 생성하여 로컬/테스트 환경에서도 파이프라인이 중단되지 않도록 합니다.

