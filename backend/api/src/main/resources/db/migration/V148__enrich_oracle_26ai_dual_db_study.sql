```

### 2-2. JPA Entity의 Oracle VECTOR 타입 매핑 (`JobPostingVector.java`)

Oracle 26ai의 `VECTOR(1536, FLOAT32)` 데이터 타입을 JPA `@Column(columnDefinition = \"VECTOR\")`으로 매핑합니다. 임베딩 벡터는 `\"[0.012, -0.045, ...]\"` 문자열 형태로 저장됩니다.

```java
@Entity
@Table(name = \"job_posting_vector\")
@Getter
@NoArgsConstructor(access = AccessLevel.PROTECTED)
public class JobPostingVector {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    @Column(name = \"job_posting_id\", nullable = false)
    private Long jobPostingId;

    @Column(name = \"chunk_content\", columnDefinition = \"CLOB\", nullable = false)
    private String chunkContent;

    /**
     * Oracle 26ai VECTOR 데이터 타입 (1536차원 임베딩 수치 배열 문자열)
     */
    @Column(name = \"embedding_vector\", columnDefinition = \"VECTOR\", nullable = false)
    private String embeddingVector;

    @Column(name = \"created_at\", nullable = false, updatable = false)
    private LocalDateTime createdAt;

    @Builder
    public JobPostingVector(Long jobPostingId, String chunkContent, String embeddingVector) {
        this.jobPostingId = jobPostingId;
        this.chunkContent = chunkContent;
        this.embeddingVector = embeddingVector;
        this.createdAt = LocalDateTime.now();
    }
}
```

### 2-3. VECTOR_DISTANCE 네이티브 쿼리 (`JobPostingVectorRepository.java`)

`@Query(nativeQuery = true)`로 Oracle 26ai 전용 `VECTOR_DISTANCE` 함수를 직접 호출합니다. 코사인 거리(Distance)가 0에 가까울수록 가장 유사한 문서입니다.

```java
public interface JobPostingVectorRepository extends JpaRepository<JobPostingVector, Long> {

    List<JobPostingVector> findByJobPostingId(Long jobPostingId);
    void deleteByJobPostingId(Long jobPostingId);

    /**
     * Oracle 26ai VECTOR_DISTANCE 코사인 유사도 Top-K 검색
     */
    @Query(value = \"SELECT v.* FROM job_posting_vector v \" +
                   \"ORDER BY VECTOR_DISTANCE(v.embedding_vector, \" +
                   \"to_vector(:queryVector), COSINE) ASC \" +
                   \"FETCH FIRST :limit ROWS ONLY\", nativeQuery = true)
    List<JobPostingVector> searchTopKSimilarChunks(
        @Param(\"queryVector\") String queryVector, @Param(\"limit\") int limit);
}
```

