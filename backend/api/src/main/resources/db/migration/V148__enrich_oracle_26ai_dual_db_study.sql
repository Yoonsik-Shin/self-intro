## 2. Oracle 26ai Vector Search 동작 메커니즘

Oracle Database 26ai는 **`VECTOR`라는 Native 데이터 타입**과 코사인 유사도, 유클리디안 거리 등의 거리 계산 함수를 기본 탑재하고 있습니다.

### 2-1. DDL 스키마 정의 (`oracle-schema.sql`)

3개 도메인(채용공고, 경험, 스터디) 벡터 테이블과 HNSW 코사인 인덱스를 정의합니다.

```sql
-- 채용공고 벡터 테이블
CREATE TABLE job_posting_vector (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_posting_id NUMBER NOT NULL,
    chunk_content CLOB NOT NULL,
    embedding_vector VECTOR(1536, FLOAT32) NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE INDEX idx_job_posting_vector_hnsw
ON job_posting_vector (embedding_vector)
ORGANIZATION INMEMORY NEIGHBOR GRAPH
DISTANCE COSINE;

-- 경험 벡터 테이블
CREATE TABLE experience_vector (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
