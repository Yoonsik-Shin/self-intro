## 3. AI Worker 로컬/운영 환경 자동 전환

AI Worker의 `application.yml`은 환경변수 유무에 따라 **로컬 H2 ↔ 운영 Oracle ATP**를 자동 전환합니다.

```yaml
spring:
  datasource:
    url: ${DB_URL:jdbc:h2:mem:workerdb;MODE=Oracle}    # 로컬: H2 Oracle 호환 모드
    username: ${DB_USERNAME:sa}
    password: ${DB_PASSWORD:}
    driver-class-name: ${DB_DRIVER:org.h2.Driver}       # 운영: oracle.jdbc.OracleDriver
  jpa:
    hibernate:
      ddl-auto: ${JPA_DDL_AUTO:update}
```

- **로컬 개발**: H2 인메모리 DB (`MODE=Oracle`)로 Oracle 방언을 에뮬레이션하여 로컬 개발 시 Oracle 설치 없이 테스트 가능.
- **K8s 운영**: 환경변수로 Oracle ATP JDBC URL(`jdbc:oracle:thin:@selfintroworker_high?TNS_ADMIN=/etc/oracle/wallet`)을 주입.

