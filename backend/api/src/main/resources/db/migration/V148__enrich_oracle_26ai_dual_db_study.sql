## 4. K8s 파드 독립화 & Wallet 보안 연동

### 4-1. mTLS Wallet Volume Mount

Oracle ATP는 강화된 보안을 위해 **mTLS(mutual TLS)** 전자 지갑(Wallet) 인증서를 요구합니다. 이를 K8s Secret으로 등록하고 Pod에 투명하게 마운트합니다.

```yaml
spec:
  containers:
    - name: backend-worker
      image: self-intro-backend-worker
      ports:
        - name: grpc
          containerPort: 9090
        - name: http
          containerPort: 8081
      envFrom:
        - configMapRef:
            name: backend-config
        - secretRef:
            name: backend-worker-db-secret
        - secretRef:
            name: backend-ai-secret
      env:
        - name: JOB_POSTING_SCHEDULER_ENABLED
          value: \"true\"
      volumeMounts:
        - name: oracle-atp-wallet
          mountPath: /etc/oracle/wallet
          readOnly: true
      resources:
        requests:
          cpu: 250m
          memory: 768Mi
        limits:
          cpu: \"1\"
          memory: 2Gi
  volumes:
    - name: oracle-atp-wallet
      secret:
        secretName: oracle-atp-worker-wallet
        optional: true
```

### 4-2. JDBC URL 설정 (TNS_ADMIN)

`TNS_ADMIN=/etc/oracle/wallet` 파라미터를 통해 Java 애플리케이션이 마운트된 Wallet 경로의 인증서를 자동으로 읽어들입니다:

```
jdbc:oracle:thin:@selfintroworker_high?TNS_ADMIN=/etc/oracle/wallet
```

### 4-3. Recreate 배포 전략

단일 VM 노드(Oracle Cloud Free Tier)에서 CPU 경합으로 인한 OOM을 방지하기 위해, `RollingUpdate` 대신 **`Recreate`** 전략을 적용합니다. 구버전 Pod가 완전히 종료된 후 신버전을 시작하여 CPU 자원 중복 사용을 차단합니다.

```yaml
spec:
  replicas: 1
  strategy:
    type: Recreate   # 구버전 완전 종료 후 신버전 기동
  revisionHistoryLimit: 3
```

