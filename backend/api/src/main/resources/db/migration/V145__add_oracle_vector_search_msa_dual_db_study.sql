## 3. K8s 파드 독립화 & Wallet 보안 연동

### 1) mTLS Wallet Volume Mount

Oracle ATP는 강화된 보안을 위해 **mTLS(mutual TLS)** 전자 지갑(Wallet) 인증서를 요구합니다. 이를 K8s Secret으로 등록하고 Pod에 투명하게 마운트합니다.

```yaml
spec:
  containers:
    - name: backend-worker
      image: self-intro-backend-worker
      volumeMounts:
        - name: oracle-atp-wallet
          mountPath: /etc/oracle/wallet
          readOnly: true
  volumes:
    - name: oracle-atp-wallet
      secret:
        secretName: oracle-atp-worker-wallet
```

### 2) JDBC URL 설정 (TNS_ADMIN)

`TNS_ADMIN=/etc/oracle/wallet` 파라미터를 통해 Java 애플리케이션이 마운트된 Wallet 경로의 인증서를 자동으로 읽어들입니다:

```
jdbc:oracle:thin:@selfintroworker_high?TNS_ADMIN=/etc/oracle/wallet
```

