## 2. Oracle 26ai Vector Search 동작 메커니즘

Oracle Database 26ai는 **`VECTOR`라는 Native 데이터 타입**과 코사인 유사도, 유클리디안 거리 등의 거리 계산 함수를 기본 탑재하고 있습니다.

### 1) DDL 스키마 정의 (`VECTOR` 타입)

```sql
CREATE TABLE job_posting_vector (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_posting_id NUMBER NOT NULL,
    chunk_content CLOB NOT NULL,
    embedding_vector VECTOR(1536, FLOAT32) NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);
```

### 2) 코사인 유사도 검색 PromQL / SQL 쿼리

`VECTOR_DISTANCE(..., COSINE)` 함수를 통해 사용자 자가소개서와 가장 유사한 채용공고 텍스트 청크를 0.001초 이내에 검색합니다:

```sql
SELECT v.*
FROM job_posting_vector v
ORDER BY VECTOR_DISTANCE(v.embedding_vector, to_vector(:queryVector), COSINE) ASC
FETCH FIRST :limit ROWS ONLY;
```

